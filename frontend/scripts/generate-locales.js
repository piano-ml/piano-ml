#!/usr/bin/env node
/**
 * Writes src/app/shared/i18n/locales.generated.ts from angular.json, so the app knows the languages it is
 * built in (switcher, hreflang, og:locale) without a second hand-written list. Not committed.
 */
const fs = require('fs');
const path = require('path');
const { readLocales } = require('./lib/i18n-config');

const OUTPUT = path.join(__dirname, '..', 'src', 'app', 'shared', 'i18n', 'locales.generated.ts');

function renderLocalesModule(locales) {
  const entries = locales.map(({ code, subPath, ogLocale }) => ({ code, subPath, ogLocale }));
  return `// Generated by scripts/generate-locales.js from the i18n section of angular.json. Do not edit.
import type { LocaleInfo } from './locale-info';

export const LOCALES: readonly LocaleInfo[] = ${JSON.stringify(entries, null, 2)};
`;
}

function main() {
  const content = renderLocalesModule(readLocales());
  const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : null;
  // Rewriting an unchanged file would retrigger watchers (ng serve, ng test --watch) for nothing.
  if (current !== content) fs.writeFileSync(OUTPUT, content, 'utf8');
  console.log(`✓ ${path.relative(process.cwd(), OUTPUT)}`);
}

if (require.main === module) main();

module.exports = { renderLocalesModule };
