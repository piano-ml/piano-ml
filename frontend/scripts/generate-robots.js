#!/usr/bin/env node
/**
 * Writes src/robots.txt: every private path is disallowed under each language's prefix, so adding a
 * language in angular.json needs no change here. Not committed.
 */
const fs = require('fs');
const path = require('path');
const { readLocales, localizedPath } = require('./lib/i18n-config');

const OUTPUT = path.join(__dirname, '..', 'src', 'robots.txt');
const SITEMAP_URL = 'https://pianoml.org/sitemap.xml';

/** The one list of paths kept out of search engines (also noindex in the app). */
const PRIVATE_PATHS = [
  '/work/',
  '/account/',
  '/desktop/',
  '/workbench/',
  '/import/',
  '/coach/',
  '/blog/legal',
  '/blog/help',
  '/score/*/reimport'
];

function renderRobots(locales, privatePaths = PRIVATE_PATHS, sitemapUrl = SITEMAP_URL) {
  const lines = ['# Generated by scripts/generate-robots.js from angular.json. Do not edit.', 'User-agent: *'];

  for (const locale of locales) {
    for (const privatePath of privatePaths) {
      lines.push(`Disallow: ${localizedPath(privatePath, locale)}`);
    }
  }

  lines.push('', `Sitemap: ${sitemapUrl}`, '');
  return lines.join('\n');
}

function main() {
  fs.writeFileSync(OUTPUT, renderRobots(readLocales()), 'utf8');
  console.log(`✓ ${path.relative(process.cwd(), OUTPUT)}`);
}

if (require.main === module) main();

module.exports = { PRIVATE_PATHS, renderRobots };
